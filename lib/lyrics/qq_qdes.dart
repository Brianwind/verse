  static final List<int> _key1 = ascii.encode('!@#)(NHL');
  static final List<int> _key2 = ascii.encode('123ZXC!@');
  static final List<int> _key3 = ascii.encode(r'!@#)(*$%');

  static String decryptAndInflate(String encryptedHex) {
    final encrypted = decodeHex(encryptedHex);
    final decrypted = decryptBytes(encrypted);
    final inflated = ZLibCodec().decode(decrypted);
    return utf8.decode(inflated);
  }

  @visibleForTesting
  static Uint8List decodeHex(String source) {
    final hex = source.trim();
    if (hex.isEmpty) {
      throw const FormatException('QRC data is empty');
    }
    if (hex.length.isOdd || !RegExp(r'^[0-9a-fA-F]+$').hasMatch(hex)) {
      throw const FormatException('QRC data is not valid hexadecimal');
    }

    final result = Uint8List(hex.length ~/ 2);
    for (var index = 0; index < result.length; index++) {
      result[index] = int.parse(
        hex.substring(index * 2, index * 2 + 2),
        radix: 16,
      );
    }
    if (result.length % 8 != 0) {
      throw const FormatException('QRC data is not aligned to an 8-byte block');
    }
    return result;
  }

  @visibleForTesting
  static Uint8List decryptBytes(Uint8List encrypted) {
    if (encrypted.isEmpty || encrypted.length % 8 != 0) {
      throw const FormatException('QRC data must contain complete DES blocks');
    }

    final key1 = _createSubKeys(_key1);
    final key2 = _createSubKeys(_key2);
    final key3 = _createSubKeys(_key3);
    final output = Uint8List(encrypted.length);

    for (var offset = 0; offset < encrypted.length; offset += 8) {
      var block = _reverseWordBytes(_readBlock(encrypted, offset));
      block = _cryptBlock(block, key1.reversed);
      block = _cryptBlock(block, key2);
      block = _cryptBlock(block, key3.reversed);
      block = _reverseWordBytes(block);
      _writeBlock(block, output, offset);
    }
    return output;
  }

  @visibleForTesting
  static Uint8List encryptBytes(Uint8List plainText) {
    if (plainText.isEmpty || plainText.length % 8 != 0) {
      throw const FormatException('QRC data must contain complete DES blocks');
    }

    final key1 = _createSubKeys(_key1);
    final key2 = _createSubKeys(_key2);
    final key3 = _createSubKeys(_key3);
    final output = Uint8List(plainText.length);

    for (var offset = 0; offset < plainText.length; offset += 8) {
      var block = _reverseWordBytes(_readBlock(plainText, offset));
      block = _cryptBlock(block, key3);
      block = _cryptBlock(block, key2.reversed);
      block = _cryptBlock(block, key1);
      block = _reverseWordBytes(block);
      _writeBlock(block, output, offset);
    }
    return output;
  }

  static int _readBlock(Uint8List bytes, int offset) {
    var result = 0;
    for (var index = 0; index < 8; index++) {
      result = (result << 8) | bytes[offset + index];
    }
    return result;
  }

  static void _writeBlock(int block, Uint8List output, int offset) {
    for (var index = 7; index >= 0; index--) {
      output[offset + index] = block & 0xff;
      block >>= 8;
    }
  }

  static List<int> _createSubKeys(List<int> keyBytes) {
    final key = _reverseWordBytes(_readBlock(Uint8List.fromList(keyBytes), 0));
    final permuted = _permute(key, 64, _permutedChoice1);
    var left = (permuted >> 28) & 0x0fffffff;
    var right = permuted & 0x0fffffff;
    final result = <int>[];

    for (final shift in _keyRotations) {
      left = ((left << shift) | (left >> (28 - shift))) & 0x0fffffff;
      right = ((right << shift) | (right >> (28 - shift))) & 0x0fffffff;
      result.add(_permute((left << 28) | right, 56, _permutedChoice2));
    }
    return result;
  }

  static int _cryptBlock(int block, Iterable<int> subKeys) {
    final initial = _permute(block, 64, _initialPermutation);
    var left = (initial >> 32) & 0xffffffff;
    var right = initial & 0xffffffff;

    for (final subKey in subKeys) {
      final nextLeft = right;
      final nextRight = (left ^ _roundFunction(right, subKey)) & 0xffffffff;
      left = nextLeft;
      right = nextRight;
    }

    return _permute((right << 32) | left, 64, _finalPermutation);
  }

  static int _roundFunction(int right, int subKey) {
    final expanded = _permute(right, 32, _expansionPermutation) ^ subKey;
    var substituted = 0;

    for (var boxIndex = 0; boxIndex < 8; boxIndex++) {
      final shift = 42 - boxIndex * 6;
      final chunk = (expanded >> shift) & 0x3f;
      final row = ((chunk & 0x20) >> 4) | (chunk & 1);
      final column = (chunk >> 1) & 0x0f;
      substituted = (substituted << 4) | _sBoxes[boxIndex][row * 16 + column];
    }

    return _permute(substituted, 32, _roundPermutation);
  }

  static int _permute(int input, int inputBits, List<int> table) {
    var output = 0;
    for (final position in table) {
      final shift = inputBits - position;
      output = (output << 1) | (shift < 0 ? 0 : (input >> shift) & 1);
    }
    return output;
  }

  static int _reverseWordBytes(int block) {
    int reverse32(int value) {
      return ((value & 0x000000ff) << 24) |
          ((value & 0x0000ff00) << 8) |
          ((value & 0x00ff0000) >> 8) |
          ((value & 0xff000000) >> 24);
    }

    final high = reverse32((block >> 32) & 0xffffffff);
    final low = reverse32(block & 0xffffffff);
    return (high << 32) | low;
  }

